          const elapsed = now - zone.createdAt;
          if (elapsed < 0) return;
          const zx = (zone.x / 100) * canvas.width;
          const zy = (zone.y / 100) * canvas.height;
          const lifePct = elapsed / zone.duration;
          const alpha = 0.6 * (1 - lifePct * 0.5); // Fade slightly over time
          const radius = 30 + Math.sin(now * 0.005) * 5; // Pulsing effect
          
          // Draw water zone circle
          ctx.beginPath();
          ctx.arc(zx, zy, radius, 0, Math.PI * 2);
          ctx.fillStyle = `rgba(34, 211, 238, ${alpha * 0.3})`;
          ctx.fill();
          ctx.strokeStyle = `rgba(34, 211, 238, ${alpha})`;
          ctx.lineWidth = 2;
          ctx.stroke();
          
          // Draw ripple effect
          const rippleRadius = radius + 10 + Math.sin(now * 0.01) * 5;
          ctx.beginPath();
          ctx.arc(zx, zy, rippleRadius, 0, Math.PI * 2);
          ctx.strokeStyle = `rgba(34, 211, 238, ${alpha * 0.5})`;
          ctx.lineWidth = 1;
          ctx.stroke();
