      enemies.current = [];
      gems.current = [];
      effects.current = [];
      waterZonesRef.current = []; // Clear water zones
      setRetroScore(0);
      setWeaponType('default');
      setAmmo(Infinity);
      totalShotsRef.current = 0;
      alienDropCountRef.current = 0;
      rowsSpawnedRef.current = 6; // Start with 6 visible rows
